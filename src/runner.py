"""Run every evaluator over every scenario, then write records and a summary.

    python -m src.runner                    # 500 scenarios, both evaluators
    python -m src.runner --limit 20         # smoke run
    python -m src.runner --jev-only         # no OPENAI_API_KEY needed
    python -m src.runner --resume           # continue an interrupted run

Design notes:

* **One failure cannot void a 500-case run.** Every task is gathered with
  `return_exceptions=True`, and the evaluators themselves already turn a failed
  request into an `EvalRecord` with `error` set. A hard error is a row in the
  results, not a traceback on the way to nothing.
* **Records stream to disk as they land.** `results/records.jsonl` is appended
  per-record, so an interrupted run keeps its work and `--resume` skips what is
  already there.
* **Warm-up requests are excluded.** The first few calls of any process pay for
  TLS handshakes and connection-pool setup. They are issued, discarded, and never
  reach the latency distribution.
* **Provenance is stamped at write time**, not typed into a document later.
"""

