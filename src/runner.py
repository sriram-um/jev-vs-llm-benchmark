def _load_existing(path: Path) -> list[EvalRecord]:
    if not path.exists():
        return []
    with path.open(encoding="utf-8") as fh:
        return [EvalRecord.model_validate_json(line) for line in fh if line.strip()]


async def main_async(args: argparse.Namespace) -> int:
    scenarios = load_dataset(settings.scenarios_path)
    if args.limit:
        scenarios = scenarios[: args.limit]

    settings.out_dir.mkdir(parents=True, exist_ok=True)
    records_path = settings.records_path

    existing = _load_existing(records_path) if args.resume else []
    if args.resume:
        print(f"resuming: {len(existing)} records already on disk")
    else:
        records_path.write_text("", encoding="utf-8")

    grouped: dict[str, list[EvalRecord]] = {}
    for record in existing:
        grouped.setdefault(record.evaluator, []).append(record)

    handle = records_path.open("a", encoding="utf-8")

    def sink(record: EvalRecord) -> None:
        handle.write(record.model_dump_json() + "\n")
        handle.flush()

    evaluators: list[tuple[Evaluator, int]] = []
    if not args.llm_only:
        evaluators.append(
            (JevEvaluator(mode=args.jev_mode), settings.jev_rpm_limit)
        )
    if not args.jev_only:
        evaluators.append(
            (LLMEvaluator(mode=args.llm_mode), settings.llm_rpm_limit)
        )

    try:
        for evaluator, rpm in evaluators:
            done = {r.scenario_id for r in grouped.get(evaluator.name, [])}
            async with evaluator:
                fresh = await run_evaluator(
                    evaluator, scenarios, rpm_limit=rpm, sink=sink, skip=done
                )
            grouped.setdefault(evaluator.name, []).extend(fresh)
    finally:
        handle.close()

    # Keep only the scenarios actually in scope this run, so `--limit` runs
    # summarise what they measured rather than mixing in a previous full run.
    wanted = {s.id for s in scenarios}
    grouped = {
        name: [r for r in records if r.scenario_id in wanted]
        for name, records in grouped.items()
    }
    grouped = {name: records for name, records in grouped.items() if records}

    if not grouped:
        print("no records produced")
        return 1

    report = build_report(
        grouped,
        scenarios,
        jev_model=settings.jev_model,
        llm_model=settings.llm_model,
    )
    settings.summary_path.write_text(
        json.dumps(report.model_dump(), indent=2) + "\n", encoding="utf-8"
    )

    print(f"\nrecords -> {records_path}  ({sum(len(v) for v in grouped.values())} rows)")
    print(f"summary -> {settings.summary_path}")
    print(f"mode    -> {report.provenance.mode}")
    if report.provenance.simulated_warning:
        print(f"\n!! {report.provenance.simulated_warning}")

    for s in report.evaluators:
        print(
            f"\n{s.evaluator} ({s.model})"
            f"\n  latency p50/p95/p99  {s.p50_ms:.1f} / {s.p95_ms:.1f} / {s.p99_ms:.1f} ms"
            f"\n  dept accuracy        {s.department_accuracy:.4f}"
            f"\n  schema conformance   {s.schema_conformance:.4f}"
            f" (retries {s.total_retries}, hard errors {s.hard_errors})"
            f"\n  total cost           ${s.total_cost_usd:.4f}"
        )
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--limit", type=int, default=None, help="only the first N scenarios")
    ap.add_argument("--jev-only", action="store_true", help="skip the LLM baseline")
    ap.add_argument("--llm-only", action="store_true", help="skip Jev")
    ap.add_argument(
        "--jev-mode",
        choices=["sdk", "http", "sim"],
        default=None,
        help="override SIMULATE_JEV (default: sim when SIMULATE_JEV=true)",
    )
    ap.add_argument(
        "--llm-mode",
        choices=["openai", "bedrock", "sim"],
        default=None,
        help="override SIMULATE_LLM / LLM_PROVIDER (default: sim when SIMULATE_LLM=true)",
    )
    ap.add_argument(
        "--resume", action="store_true", help="keep existing records and fill the gaps"
    )
    args = ap.parse_args()
    return asyncio.run(main_async(args))


if __name__ == "__main__":
    raise SystemExit(main())
