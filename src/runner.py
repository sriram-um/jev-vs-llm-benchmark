def summarise_evaluator(
    records: list[EvalRecord], scenarios: list[Scenario]
) -> tuple[EvaluatorSummary, list[dict[str, float]]]:
    """Aggregate one evaluator's records. Returns the summary and its ECE bins."""
    truth = {s.id: s.truth for s in scenarios}
    dept_truth = {sid: t.department for sid, t in truth.items()}
    urgency_truth = {sid: t.urgency_level for sid, t in truth.items()}
    escalate_truth = {sid: t.escalate_supervisor for sid, t in truth.items()}

    # Latency excludes hard errors, which have no meaningful duration.
    latencies = [
        r.latency_ms for r in records if r.error is None and r.latency_ms == r.latency_ms
    ]

    dept_pairs = [
        (r.prediction.department if r.prediction else None, dept_truth[r.scenario_id])
        for r in records
    ]
    escalate_pairs = [
        (
            r.prediction.escalate_supervisor if r.prediction else None,
            escalate_truth[r.scenario_id],
        )
        for r in records
    ]

    discrete_errors = metrics.urgency_errors(records, urgency_truth)
    expected_errors = metrics.urgency_errors(records, urgency_truth, use_expected=True)

    exact = sum(
        1
        for r in records
        if r.prediction is not None and r.prediction == truth[r.scenario_id]
    )

    # --- calibration -----------------------------------------------------
    # Only records that actually carry a probability participate. An evaluator
    # that exposes none gets None, not zero.
    dept_probs = [
        (r.p_department, r.prediction.department == dept_truth[r.scenario_id])
        for r in records
        if r.p_department is not None and r.prediction is not None
    ]
    ece_dept: float | None = None
    dept_bins: list[dict[str, float]] = []
    if dept_probs:
        ece_dept, dept_bins = metrics.ece(
            [p for p, _ in dept_probs],
            [c for _, c in dept_probs],
            settings.ece_bins,
        )

    esc_probs = [
        (r.p_escalate, escalate_truth[r.scenario_id])
        for r in records
        if r.p_escalate is not None
    ]
    ece_esc: float | None = None
    brier_esc: float | None = None
    if esc_probs:
        ece_esc, _ = metrics.ece(
            [p for p, _ in esc_probs],
            [o for _, o in esc_probs],
            settings.ece_bins,
        )
        brier_esc = metrics.brier(
            [p for p, _ in esc_probs], [o for _, o in esc_probs]
        )

    # The same computation run on Jev's `confidence` statistic instead of a real
    # probability. Reported ONLY to show that the two are not interchangeable;
    # `confidence` is a peakedness measure, not a claim about correctness.
    conf_pairs = [
        (
            r.confidence_department,
            r.prediction.department == dept_truth[r.scenario_id],
        )
        for r in records
        if r.confidence_department is not None and r.prediction is not None
    ]
    ece_on_conf: float | None = None
    if conf_pairs:
        ece_on_conf, _ = metrics.ece(
            [p for p, _ in conf_pairs],
            [c for _, c in conf_pairs],
            settings.ece_bins,
        )

    proxies = [r.p_first_token_proxy for r in records if r.p_first_token_proxy is not None]
    mean_proxy = (sum(proxies) / len(proxies)) if proxies else None

    costs = metrics.cost_totals(records)
    lat = metrics.percentiles(latencies)
    first = records[0]

    summary = EvaluatorSummary(
        evaluator=first.evaluator,
        model=first.model,
        source=first.source,
        n=len(records),
        p50_ms=lat["p50_ms"],
        p95_ms=lat["p95_ms"],
        p99_ms=lat["p99_ms"],
        mean_ms=lat["mean_ms"],
        department_accuracy=metrics.accuracy(dept_pairs),
        department_macro_f1=metrics.macro_f1(dept_pairs, DEPARTMENTS),
        escalate_accuracy=metrics.accuracy(escalate_pairs),
        urgency_mae_0_100=metrics.mae(discrete_errors),
        urgency_rmse_0_100=metrics.rmse(discrete_errors),
        urgency_mae_expected_0_100=(
            metrics.mae(expected_errors) if expected_errors else None
        ),
        exact_match_all_three=exact / len(records) if records else float("nan"),
        schema_conformance=metrics.schema_conformance(records),
        total_retries=sum(r.retries for r in records),
        hard_errors=sum(1 for r in records if r.error is not None),
        ece_department=ece_dept,
        ece_escalate=ece_esc,
        brier_escalate=brier_esc,
        ece_department_on_confidence=ece_on_conf,
        mean_first_token_proxy=mean_proxy,
        total_input_tokens=int(costs["total_input_tokens"]),
        total_output_tokens=int(costs["total_output_tokens"]),
        total_cost_usd=costs["total_cost_usd"],
        cost_per_1k_decisions_usd=costs["cost_per_1k_decisions_usd"],
    )
    return summary, dept_bins


def _git_sha() -> str | None:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            capture_output=True,
            text=True,
            timeout=5,
            cwd=Path(__file__).resolve().parent.parent,
        )
        return out.stdout.strip() or None if out.returncode == 0 else None
    except Exception:
        return None


def build_report(
    grouped: dict[str, list[EvalRecord]],
    scenarios: list[Scenario],
    *,
    jev_model: str,
    llm_model: str,
) -> SummaryReport:
    summaries: list[EvaluatorSummary] = []
    reliability: dict[str, list[dict[str, float]]] = {}
    latency_samples: dict[str, list[float]] = {}

    for name, records in grouped.items():
        summary, bins = summarise_evaluator(records, scenarios)
        summaries.append(summary)
        if bins:
            reliability[name] = bins
        latency_samples[name] = sorted(
            r.latency_ms for r in records if r.error is None and r.latency_ms == r.latency_ms
        )

    sources = {r.source for records in grouped.values() for r in records}
    mode = sources.pop() if len(sources) == 1 else "mixed"

    provenance = Provenance(
        generated_at=datetime.now(timezone.utc).isoformat(timespec="seconds"),
        mode=mode,  # type: ignore[arg-type]
        jev_model=jev_model,
        llm_model=llm_model,
        n_scenarios=len(scenarios),
        dataset_sha256=dataset_sha256(settings.scenarios_path),
        seed=settings.seed,
        git_sha=_git_sha(),
        simulated_warning=SIMULATED_WARNING if mode != "live" else None,
    )
    return SummaryReport(
        provenance=provenance,
        evaluators=summaries,
        reliability=reliability,
        latency_samples=latency_samples,
    )


