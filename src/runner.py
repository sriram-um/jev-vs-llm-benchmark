SIMULATED_WARNING = (
    "SIMULATED -- not a measurement. Latency, token counts, accuracy and "
    "probabilities were generated by the local simulators in src/clients/, whose "
    "parameters we chose. The Jev simulator samples where the true answer sits "
    "inside the distribution it reports, so its calibration is true by "
    "construction and its residual ECE is finite-sample noise, not a property "
    "of any model. "
    "These numbers describe those simulators; they are not evidence about either "
    "system. Only a run with mode=live measures anything."
)


# ---------------------------------------------------------------------------
# Execution
# ---------------------------------------------------------------------------


async def _run_one(
    evaluator: Evaluator,
    scenario: Scenario,
    semaphore: asyncio.Semaphore,
    limiter: RateLimiter,
) -> EvalRecord:
    """Always returns a record; never raises.

    Containing the failure here rather than at a `gather(return_exceptions=True)`
    is deliberate: it keeps the record stream complete, so an evaluator that dies
    on scenario 300 still produces 500 rows and the summary's `hard_errors` count
    tells you what happened.
    """
    try:
        async with semaphore:
            await limiter.acquire()
            return await evaluator.evaluate(scenario)
    except Exception as exc:
        return EvalRecord(
            scenario_id=scenario.id,
            evaluator=evaluator.name,
            model="unknown",
            source="live",
            prediction=None,
            latency_ms=float("nan"),
            schema_ok=False,
            error=f"{type(exc).__name__}: {exc}",
        )


async def _warm_up(evaluator: Evaluator, scenario: Scenario, n: int) -> None:
    """Issue and discard `n` requests so setup costs miss the measurement."""
    for _ in range(n):
        try:
            await evaluator.evaluate(scenario)
        except Exception:
            # A failing warm-up is not fatal -- the real attempts will record it.
            pass


async def run_evaluator(
    evaluator: Evaluator,
    scenarios: list[Scenario],
    *,
    rpm_limit: int,
    sink,
    skip: set[str],
) -> list[EvalRecord]:
    pending = [s for s in scenarios if s.id not in skip]
    if not pending:
        return []

    await _warm_up(evaluator, pending[0], settings.warmup_requests)

    semaphore = asyncio.Semaphore(settings.concurrency)
    limiter = RateLimiter(rpm_limit)
    tasks = [
        asyncio.create_task(_run_one(evaluator, s, semaphore, limiter))
        for s in pending
    ]

    records: list[EvalRecord] = []
    with tqdm(total=len(tasks), desc=evaluator.name, unit="req") as bar:
        for coro in asyncio.as_completed(tasks):
            result = await coro
            if isinstance(result, BaseException):  # pragma: no cover - defensive
                bar.update(1)
                continue
            records.append(result)
            sink(result)
            bar.update(1)
    return records


